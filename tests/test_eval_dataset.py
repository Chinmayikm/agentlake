"""Contract tests for the golden dataset, checked as files.

No Qdrant, no Postgres, no network: every assertion here reads
eval/golden/*.yaml and eval/golden/corpus_paths.txt off disk. That is the
point -- a label that points at a document the corpus does not contain scores
hit@k = 0 forever and reads as a retrieval regression, so it has to be caught
by the suite rather than by a confused human three runs later.
"""

from __future__ import annotations

from collections import Counter

import pytest

from eval.dataset import (
    CI_SUBSET_SIZE,
    DATASET_VERSION,
    DIFFICULTIES,
    PROJECTS,
    TYPES,
    DatasetError,
    GoldenExample,
    ci_subset,
    load_corpus_paths,
    load_dataset,
)

EXAMPLES = load_dataset()
CORPUS_PATHS = load_corpus_paths()


# ---------------------------------------------------------------------------
# 1. The set loads, and its identities are stable
# ---------------------------------------------------------------------------


def test_the_dataset_loads_and_is_not_trivially_small() -> None:
    """A dataset that silently shrank -- a YAML parse that dropped a block, a
    file renamed out of the glob -- would raise every metric by scoring fewer,
    easier examples, with no error anywhere."""
    assert len(EXAMPLES) >= 75
    assert {e.project for e in EXAMPLES} == set(PROJECTS), "a whole project file went missing"


def test_every_key_is_unique_and_project_scoped() -> None:
    """`key` is the identity eval_results rows are attributed to and the seed
    for the judge's per-example RNG. A duplicate would silently merge two
    examples' history; a mis-scoped one would break the stratified sampling
    that reads the project off the key."""
    keys = [e.key for e in EXAMPLES]
    assert len(keys) == len(set(keys))
    assert all(e.key.startswith(f"{e.project}-") for e in EXAMPLES)


def test_every_example_declares_a_closed_vocabulary_tag() -> None:
    assert {e.project for e in EXAMPLES} <= set(PROJECTS)
    assert {e.type for e in EXAMPLES} <= set(TYPES)
    assert {e.difficulty for e in EXAMPLES} <= set(DIFFICULTIES)


# ---------------------------------------------------------------------------
# 2. Labels resolve against the real corpus
# ---------------------------------------------------------------------------


def test_corpus_paths_file_is_present_and_parsed() -> None:
    """Generated by `python -m eval corpus-paths` and committed, so the checks
    below need no Qdrant. If this is empty the parser broke -- which it did
    once, by keeping the project column as part of the path."""
    assert len(CORPUS_PATHS) >= 90
    assert all(" " not in path for path in CORPUS_PATHS)
    assert any(p.endswith("docs/design.html") for p in CORPUS_PATHS)


@pytest.mark.parametrize("example", [e for e in EXAMPLES if e.answerable], ids=lambda e: e.key)
def test_every_expected_source_matches_a_real_document(example: GoldenExample) -> None:
    """An unresolvable prefix is a label bug that is indistinguishable, in the
    metric, from the retriever missing."""
    for prefix in example.expected_sources:
        assert any(path.startswith(prefix) for path in CORPUS_PATHS), (
            f"{example.key}: expected_source {prefix!r} matches no corpus document"
        )


@pytest.mark.parametrize("example", [e for e in EXAMPLES if e.answerable], ids=lambda e: e.key)
def test_written_from_is_a_real_document_and_is_scored(example: GoldenExample) -> None:
    """The authoring-bias rule (ADR-008 §3), enforced rather than promised: the
    question was written from a source file, and that file is one of the ones
    the example is scored against. An example written from one file but scored
    against another is either a typo or a question that does not test what it
    claims to."""
    assert example.written_from_path in CORPUS_PATHS
    assert any(example.written_from.startswith(p) for p in example.expected_sources)


# ---------------------------------------------------------------------------
# 3. The CI subset
# ---------------------------------------------------------------------------


def test_ci_subset_is_exactly_the_size_the_thresholds_assume() -> None:
    """eval/baseline.json's floors are derived from 1/N being the smallest
    movement one example can cause (1/25 = 0.04). Changing N silently would
    leave the thresholds calibrated for a set that no longer exists."""
    assert len(ci_subset(EXAMPLES)) == CI_SUBSET_SIZE


def test_ci_subset_is_stratified_across_every_axis() -> None:
    """A subset concentrated in one project or one type measures that slice,
    not the system. Each axis has three values, so no bucket may fall below
    a quarter of 25 -- loose enough to survive an added example, tight enough
    to reject a subset that is two-thirds Kafka."""
    subset = ci_subset(EXAMPLES)
    floor = CI_SUBSET_SIZE // 4
    for axis in ("project", "type", "difficulty"):
        counts = Counter(getattr(e, axis) for e in subset)
        expected = {"project": PROJECTS, "type": TYPES, "difficulty": DIFFICULTIES}[axis]
        assert set(counts) == set(expected)
        assert min(counts.values()) >= floor, f"{axis} is lopsided: {dict(counts)}"


def test_ci_subset_is_not_concentrated_in_a_handful_of_topics() -> None:
    """Stratifying by project and type is not enough: a Kafka slice that is
    five-eighths log-compaction questions measures log compaction. Topic is the
    key minus its trailing number."""
    topics = Counter(e.key.rsplit("-", 1)[0] for e in ci_subset(EXAMPLES))
    assert max(topics.values()) <= 3, f"topic concentration: {topics.most_common(3)}"


def test_ci_subset_includes_an_unanswerable_example() -> None:
    """"Say plainly when the corpus does not answer the question" is an
    instruction v4 gives and v5 removes. Without one of these in the gated
    subset, the degraded prompt would only look terser."""
    assert any(not e.answerable for e in ci_subset(EXAMPLES))


# ---------------------------------------------------------------------------
# 4. Unanswerable examples are consistently marked
# ---------------------------------------------------------------------------


def test_unanswerable_examples_exist_and_carry_no_sources() -> None:
    unanswerable = [e for e in EXAMPLES if not e.answerable]
    assert len(unanswerable) >= 3
    for example in unanswerable:
        assert example.expected_sources == ()
        assert example.written_from == "(not in the corpus)"


# ---------------------------------------------------------------------------
# 5. Validation rejects what it should
# ---------------------------------------------------------------------------


def _write(tmp_path, body: str):
    (tmp_path / "kafka.yaml").write_text(
        f"dataset_version: {DATASET_VERSION}\nproject: kafka\nexamples:\n{body}", encoding="utf-8"
    )
    return tmp_path


_VALID = """\
  - key: kafka-x-001
    question: "q?"
    expected_answer: "a"
    expected_sources: [docs/design.html]
    written_from: "docs/design.html#S"
    difficulty: easy
    type: factual
"""


def test_a_valid_minimal_example_loads(tmp_path) -> None:
    assert len(load_dataset(_write(tmp_path, _VALID))) == 1


@pytest.mark.parametrize(
    ("old", "new", "match"),
    [
        # A key that does not fit the shape, so the stable-identity convention
        # is not actually enforced by anything.
        ("kafka-x-001", "kafka_x_1", "key must match"),
        # A key claiming a different project from the file it lives in -- the
        # stratified sampling reads the project off the key.
        ("kafka-x-001", "flink-x-001", "must start with the file's project"),
        # Written from one file, scored against another.
        ('written_from: "docs/design.html#S"', 'written_from: "docs/ops.html#S"',
         "not under any expected_source"),
        ("difficulty: easy", "difficulty: trivial", "difficulty must be"),
        ("type: factual", "type: opinion", "type must be"),
        ('expected_answer: "a"', 'expected_answer: ""', "expected_answer.*required"),
        ('written_from: "docs/design.html#S"', 'written_from: ""',
         "written_from.*required"),
    ],
)
def test_validation_rejects_a_broken_example(tmp_path, old: str, new: str, match: str) -> None:
    """Each of these is a mistake that would otherwise produce a plausible
    number over a set nobody chose -- which is why load_dataset raises on the
    first problem instead of skipping the example."""
    body = _VALID.replace(old, new)
    assert body != _VALID, "the mutation did not apply -- the test would pass vacuously"
    with pytest.raises(DatasetError, match=match):
        load_dataset(_write(tmp_path, body))


def test_an_answerable_example_needs_at_least_one_source(tmp_path) -> None:
    body = _VALID.replace(
        "    expected_sources: [docs/design.html]\n", "    expected_sources: []\n"
    )
    with pytest.raises(DatasetError, match="at least one expected_source"):
        load_dataset(_write(tmp_path, body))


def test_an_unanswerable_example_must_not_claim_sources(tmp_path) -> None:
    """If the corpus does cover it, the example is answerable -- and scoring it
    as unanswerable would teach the judge to reward a refusal."""
    body = _VALID + "    answerable: false\n"
    with pytest.raises(DatasetError, match="must have no expected_sources"):
        load_dataset(_write(tmp_path, body))


def test_duplicate_keys_across_files_are_rejected(tmp_path) -> None:
    _write(tmp_path, _VALID)
    (tmp_path / "flink.yaml").write_text(
        f"dataset_version: {DATASET_VERSION}\nproject: kafka\nexamples:\n{_VALID}", encoding="utf-8"
    )
    with pytest.raises(DatasetError, match="duplicate key"):
        load_dataset(tmp_path)


def test_a_stale_dataset_version_is_rejected(tmp_path) -> None:
    """The version is recorded on every eval_run. A file left at an old one
    would produce results that look comparable and are not."""
    path = _write(tmp_path, _VALID) / "kafka.yaml"
    path.write_text(path.read_text().replace(DATASET_VERSION, "v0"), encoding="utf-8")
    with pytest.raises(DatasetError, match="dataset_version"):
        load_dataset(tmp_path)
