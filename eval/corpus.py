"""What is actually in the corpus, read from the production store.

Used by `python -m eval corpus-paths` to regenerate
eval/golden/corpus_paths.txt, which the golden-set contract test then checks
`expected_sources` against with no Qdrant running.
"""

from __future__ import annotations

from collections import Counter


def corpus_documents() -> Counter[tuple[str, str]]:
    """(project, source_path) -> chunk count, for the ingested corpus_version.

    Scrolls rather than searches: this is an inventory question, not a ranking
    one, and `search()` would need a query vector to answer it. The
    corpus_version filter is the same one `search()` applies, so this reports
    exactly the documents that are retrievable -- not merely the ones present.
    """
    from qdrant_client.http import models as qm

    from services.rag.qdrant_store import default_store

    store = default_store()
    client = store._get_client()
    condition = qm.Filter(
        must=[
            qm.FieldCondition(key="kind", match=qm.MatchValue(value="chunk")),
            qm.FieldCondition(
                key="corpus_version", match=qm.MatchValue(value=store.corpus_version)
            ),
        ]
    )

    counts: Counter[tuple[str, str]] = Counter()
    offset = None
    while True:
        points, offset = client.scroll(
            collection_name=store.collection,
            scroll_filter=condition,
            limit=500,
            offset=offset,
            with_payload=["project", "source_path"],
        )
        for point in points:
            counts[(point.payload["project"], point.payload["source_path"])] += 1
        if offset is None:
            return counts


def render_corpus_paths(counts: Counter[tuple[str, str]], corpus_version: str) -> str:
    """The committed corpus_paths.txt: chunk count, project, source_path.

    The chunk count is carried deliberately. A path with one chunk is a stub
    (Flink's `_index.md` files are a single front-matter line), and an
    expected_source pointing only at one of those is a label that can never be
    hit for a reason that has nothing to do with retrieval quality.
    """
    lines = [
        "# Generated by `python -m eval corpus-paths` -- do not edit by hand.",
        f"# corpus_version: {corpus_version}",
        f"# {len(counts)} documents, {sum(counts.values())} chunks",
        "#",
        "# chunks  project   source_path",
    ]
    for (project, source_path), n in sorted(counts.items()):
        lines.append(f"{n:8d}  {project:8s}  {source_path}")
    return "\n".join(lines) + "\n"
